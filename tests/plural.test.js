import { test } from 'node:test';
import assert from 'node:assert/strict';
import { plural } from '../src/lib/plural.js';

test('plural: 1 гравець, 2–4 гравці, 5+ гравців; 11–14 — завжди «гравців»; 21, 22, 101', () => {
  const f = (n) => `${n} ${plural(n, ['гравець', 'гравці', 'гравців'])}`;
  assert.deepEqual([0, 1, 2, 4, 5, 8, 11, 12, 14, 21, 22, 25, 101, 111, -2].map(f),
    ['0 гравців', '1 гравець', '2 гравці', '4 гравці', '5 гравців', '8 гравців', '11 гравців', '12 гравців', '14 гравців', '21 гравець', '22 гравці', '25 гравців', '101 гравець', '111 гравців', '-2 гравці']);
});
